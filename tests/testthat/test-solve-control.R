# The argument list of the generated solve entries, the order cap of the
# multistep methods and stability limit detection.

skip_on_cran()

# -- Models --------------------------------------------------------------------

# A forced, weakly damped stiff oscillator.
eqns  <- c(x = "-a*x - w*y + sin(time)", y = "w*x - a*y", z = "-z + x")
times <- seq(0, 50, length.out = 11)
pars  <- c(x = 1, y = 0, z = 0, a = 1, w = 100)

osc_bdf   <- cppODE(eqns, stepTrace = TRUE, modelname = "oc_bdf", compile = FALSE)
osc_adams <- cppODE(eqns, method = "adams", deriv = FALSE, stepTrace = TRUE,
                    modelname = "oc_adams", compile = FALSE)
osc_rev   <- cppODE(eqns, derivMode = "reverse", modelname = "oc_rev", compile = FALSE)
osc_rb4   <- cppODE(eqns, method = "rb4", modelname = "oc_rb4", compile = FALSE)
compile(osc_bdf, osc_adams, osc_rev, osc_rb4, output = "test_order_control",
        cores = test_cores())

has_cvode <- isTRUE(cvodeConfig$available)
if (has_cvode) {
  osc_cv <- cvode(eqns, deriv = TRUE, modelname = "oc_cv", compile = FALSE)
  compile(osc_cv, output = "test_order_control_cvode", cores = test_cores())
}

ref <- solveODE(osc_rb4, times, pars, abstol = 1e-11, reltol = 1e-11)
ref_grad <- apply(ref$tangent, 3, sum)
solve_at <- function(model, tol, ...)
  solveODE(model, times, pars, abstol = tol, reltol = tol, ...)

# -- The argument list ---------------------------------------------------------

test_that("the solve entry reads its argument list by name and checks it", {
  args <- cppDE:::.solveArgs(osc_bdf, times, pars)$args
  sym  <- cppDE:::.nativeSym("solve_oc_bdf")
  call <- function(a) cppDE:::.callSym(sym, a)
  expect_equal(call(args)$variable, solve_at(osc_bdf, 1e-6)$variable)

  expect_error(call(modifyList(args, list(abi = 0L))), "solve ABI 1 and called with ABI 0")
  expect_error(call(c(args, list(future = 1))), "unknown solve argument 'future'")
  expect_error(call(args[names(args) != "abstol"]), "'abstol' is missing")
  expect_error(call(modifyList(args, list(maxsteps = 1e6))), "'maxsteps' has type double")
  expect_error(call(modifyList(args, list(abstol = c(1, 2)))), "'abstol' must have length 1")
  expect_error(call(unname(args)), "must be named")
})

test_that("a model handle from another argument list is refused", {
  old <- osc_bdf
  attr(old, "solveAbi") <- NULL
  expect_error(solveODE(old, times, pars), "generated by an older cppDE")
})

# -- maxOrder ------------------------------------------------------------------

test_that("maxOrder caps the order of BDF and Adams", {
  free <- solve_at(osc_bdf, 1e-6)
  capd <- solve_at(osc_bdf, 1e-6, maxOrder = 3)
  expect_identical(max(free$trace$q), 5L)
  expect_lte(max(capd$trace$q), 3)
  expect_lt(max(abs(capd$variable - ref$variable)), 1e-4)

  ad <- solve_at(osc_adams, 1e-6, maxOrder = 4)
  expect_lte(max(ad$trace$q), 4)
  expect_lt(max(abs(ad$variable - ref$variable)), 1e-4)
})

# -- STALD ---------------------------------------------------------------------

test_that("stald lowers the order and the step count", {
  off <- solve_at(osc_bdf, 1e-4)
  on  <- solve_at(osc_bdf, 1e-4, stald = TRUE)
  expect_lt(on$diagnostics$accepted, 0.6 * off$diagnostics$accepted)
  late <- function(s) s$trace$q[s$trace$t > 10]
  expect_true(all(late(off) == 5))
  expect_gt(mean(late(on) < 5), 0.5)
})

test_that("values, sensitivities and the reverse gradient hold under stald", {
  on <- solve_at(osc_bdf, 1e-6, stald = TRUE)
  expect_lt(max(abs(on$variable - ref$variable)), 1e-4)
  expect_lt(max(abs(apply(on$tangent, 3, sum) - ref_grad)), 1e-3)

  W <- matrix(1, length(times), 3)
  rev_on <- solve_at(osc_rev, 1e-6, stald = TRUE, cotangent = W)
  expect_lt(max(abs(drop(rev_on$cotangent) - ref_grad)), 5e-3)
})

test_that("a batch condition takes its own maxOrder and stald", {
  conds <- list(plain = list(), stald = list(stald = TRUE), capped = list(maxOrder = 2))
  b <- solveODEBatch(osc_bdf, conds, times = times, parms = pars,
                     abstol = 1e-4, reltol = 1e-4, cores = 1)
  one <- function(...) solve_at(osc_bdf, 1e-4, ...)$diagnostics$accepted
  expect_identical(b$plain$diagnostics$accepted, one())
  expect_identical(b$stald$diagnostics$accepted, one(stald = TRUE))
  expect_lte(max(b$capped$trace$q), 2)
})

test_that("maxOrder and stald are checked against the method", {
  expect_error(solve_at(osc_rb4, 1e-6, maxOrder = 2), "multistep methods")
  expect_error(solve_at(osc_bdf, 1e-6, maxOrder = 6), "from 1 to 5")
  expect_error(solve_at(osc_bdf, 1e-6, maxOrder = 2.5), "whole number")
  expect_error(solve_at(osc_adams, 1e-6, maxOrder = 13), "from 1 to 12")
  expect_error(solve_at(osc_adams, 1e-6, stald = TRUE), "\"bdf\" only")
  expect_error(solve_at(osc_bdf, 1e-6, stald = NA), "TRUE or FALSE")
})

# -- CVODE ---------------------------------------------------------------------

test_that("cvode() takes maxOrder and stald", {
  skip_if_not(has_cvode, "CVODE backend not available")
  off  <- solve_at(osc_cv, 1e-4)
  on   <- solve_at(osc_cv, 1e-4, stald = TRUE)
  capd <- solve_at(osc_cv, 1e-4, maxOrder = 2)
  expect_identical(off$diagnostics$last_order, 5L)
  expect_lt(on$diagnostics$accepted, 0.8 * off$diagnostics$accepted)
  expect_lte(capd$diagnostics$last_order, 2L)
  expect_lt(max(abs(on$variable - ref$variable)), 1e-2)
})
